  function normalizeLocale(locale) {
    return String(locale || "").toLowerCase().startsWith("en") ? "en" : defaultLocale;
  }

  function getInitialLocale() {
    try {
      return normalizeLocale(localStorage.getItem(storageKey) || navigator.language);
    } catch {
      return defaultLocale;
    }
  }

  function setLocale(locale) {
    const normalized = normalizeLocale(locale);
    try {
      localStorage.setItem(storageKey, normalized);
    } catch {
      // Local storage can be unavailable in restricted contexts.
    }
    document.documentElement.lang = normalized;
    return normalized;
  }

  function t(key, locale, params = {}) {
    const normalized = normalizeLocale(locale);
    const template = dictionaries[normalized]?.[key] ?? dictionaries[defaultLocale]?.[key] ?? key;
    return String(template).replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
  }

  window.VaultOtpI18n = {
    defaultLocale,
    locales: [defaultLocale, "en"],
    dictionaries,
    getInitialLocale,
    normalizeLocale,
    setLocale,
    t,
  };
